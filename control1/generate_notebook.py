        "    \"\"\"\n",
        "    img = imagen_suavizada.copy().astype(np.float64)\n",
        "    Kh = np.array([[-1.0, 0.0, 1.0], [-2.0, 0.0, 2.0], [-1.0, 0.0, 1.0]], dtype=np.float64)\n",
