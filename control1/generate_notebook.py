        "def rgb_a_yuv(img_rgb: np.ndarray) -> dict[str, np.ndarray]:\n",
        "    \"\"\"\n",
        "    Transformación lineal al espacio YUV mediante producto matricial exacto de clase:\n",
        "        Y =  0.2990 * R + 0.5876 * G + 0.1140 * B\n",
        "        U = -0.1470 * R - 0.2890 * G + 0.4360 * B\n",
        "        V =  0.6150 * R - 0.5150 * G - 0.1000 * B\n",
