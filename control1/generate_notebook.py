        "## MÓDULO 5: Motor de Convolución 2D Manual y Filtros de Paso Bajo (Suavizado)\n",
        "\n",
        "### ⚙️ Convolución Espacial Discreta 2D\n",
        "La convolución formal de una imagen $I$ con un kernel $K$ de dimensión impar $N \\times N$ ($N = 2p + 1$) rota espacialmente el kernel $180^\\circ$ ($K_{\\text{flip}}(u, v) = K(N-1-u, N-1-v)$) y evalúa el producto interno local:\n",
        "$$S(i, j) = \\left\\lfloor \\sum_{u=0}^{N-1} \\sum_{v=0}^{N-1} I_{\\text{pad}}(i+u, j+v) \\cdot K_{\\text{flip}}(u, v) \\right\\rfloor$$\n",
        "\n",
        "### 📏 Demostración de Dimensiones y Recuperación de Bordes\n",
        "- **Con `recuperar_bordes=True`:** Se aplica padding por reflexión (espejo) de grosor $p = \\lfloor N / 2 \\rfloor$ en las 4 fronteras. La imagen de salida conserva exactamente sus dimensiones originales $(H, W)$.\n",
        "- **Con `recuperar_bordes=False`:** No se rellena la periferia; el kernel solo se evalúa donde cabe completamente en la matriz. La imagen se reduce a:\n",
        "$$(H - 2p) \\times (W - 2p) = (H - 2\\lfloor N/2 \\rfloor) \\times (W - 2\\lfloor N/2 \\rfloor)$$\n",
        "Por ejemplo, una matriz de $512 \\times 512$ operada con un kernel $5 \\times 5$ ($p = 2$) se reduce a $508 \\times 508$ (perdiendo 4 filas y 4 columnas).\n",
        "\n",
        "### 🛡️ Aplicación de la Función Piso (`np.floor`)\n",
        "Los niveles de intensidad de las imágenes digitales corresponden a magnitudes discretas. Aplicar la función piso (`np.floor`) garantiza que los resultados acumulados de coma flotante se trunquen a números enteros sin provocar desbordamientos numéricos por encima de los techos dinámicos ($255$ o $65535$).\n",
        "\n",
        "### 🌊 Filtros de Paso Bajo Implementados:\n",
        "1. **Filtro Promedio:** Todos los pesos valen $1 / N^2$ (suma total $= 1.0$). Suavizado uniforme pero borra bordes.\n",
        "2. **Filtro Gaussiano 2D:** Ponderación radial basada en la campana de Gauss:\n",
        "$$G(x,y) = \\frac{1}{2\\pi\\sigma^2} \\exp\\left( -\\frac{x^2+y^2}{2\\sigma^2} \\right)$$\n",
        "**REGLA CRÍTICA DE NORMALIZACIÓN:** La rejilla finita discretizada no suma 1.0. Es **obligatorio normalizar dividiendo cada peso entre `np.sum(kernel)`** para que la suma total sea exactamente `1.0`; de lo contrario, la imagen se oscurece artificialmente alterando la calibración física.\n",
        "3. **Filtro de Mediana (No Lineal):** Ordena los valores del vecindario $N \\times N$ y selecciona el percentil 50%. Es el filtro óptimo para eliminar ruido impulsivo (\"sal y pimienta\") y artefactos de reconstrucción sin desenfocar los bordes anatómicos en RM y TAC.\n"
