        "    S = np.zeros_like(c_max)\n",
        "    V = c_max.copy()\n",
        "    \n",
        "    mask_d = (delta != 0.0)\n",
        "    mask_r = (c_max == r) & mask_d\n",
        "    mask_g = (c_max == g) & mask_d & (~mask_r)\n",
        "    mask_b = (c_max == b) & mask_d & (~mask_r) & (~mask_g)\n",
        "    \n",
        "    H[mask_r] = 60.0 * (((g[mask_r] - b[mask_r]) / delta[mask_r]) % 6.0)\n",
