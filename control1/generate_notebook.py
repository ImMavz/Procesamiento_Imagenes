        "    Detector estadístico no lineal: R = 1 - (1 / (1 + sigma^2)) reescalado a [0, 255].\n",
        "    Calcula la varianza local sobre vecindarios NxN.\n",
        "    \"\"\"\n",
        "    if tamano_ventana % 2 == 0:\n",
        "        raise ValueError(\"El tamaño de la ventana debe ser impar.\")\n",
