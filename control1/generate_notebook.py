        "  * $\\sigma = 2.0$ y kernel $7\\times 7$: Campana muy ancha; promedia agresivamente con vecinos lejanos. Si bien reduce drásticamente la varianza del ruido, **destruye los bordes y fusiona microestructuras cerebrales** (como las circunvoluciones del hipocampo y la amígdala, que en clínica son como pepitas de una mora).\n"
