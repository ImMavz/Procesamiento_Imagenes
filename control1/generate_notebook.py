        "### 💡 Fundamento Estadístico No Lineal\n",
        "A diferencia de Sobel (gradiente direccional / primera derivada) y del Laplaciano (curvatura isotrópica / segunda derivada), el **Operador Basado en la Varianza Local** no utiliza convolución con máscaras diferenciales discretas. Modela directamente la dispersión de energía local en un vecindario $N \\times N$:\n",
