        "\n",
        "def aplicar_sobel(imagen_suavizada: np.ndarray, recuperar_bordes: bool = True) -> dict[str, np.ndarray]:\n",
        "    \"\"\"\n",
        "    Aplica operador de Sobel sobre la imagen suavizada calculando:\n",
        "    - Gx: Componente horizontal\n",
        "    - Gy: Componente vertical\n",
        "    - Magnitud: np.floor(sqrt(Gx^2 + Gy^2))\n",
