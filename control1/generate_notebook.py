        "\n",
        "#### 3. ¿Por qué el ruido de fondo en RM es Rayleigh y no Gaussiano?\n",
        "> **Respuesta Técnica:** Las bobinas de RM miden dos señales en cuadratura $I$ (en fase) y $Q$ (en cuadratura) en el dominio de Fourier ($k$-space). Cada canal está contaminado por ruido blanco Gaussiano independiente. Al reconstruir la imagen final como la magnitud euclidiana $M = \\sqrt{I^2 + Q^2}$, en las zonas de fondo de aire donde no hay señal biológica ($I \\approx 0, Q \\approx 0$), la distribución resultante de la raíz de la suma de dos variables normales centradas al cuadrado es matemáticamente una distribución de **Rayleigh**.\n",
        "\n",
        "#### 4. ¿Por qué en TAC el ruido es de Poisson y el fondo vale aproximadamente $-1000\\text{ HU}$?\n",
        "> **Respuesta Técnica:** La emisión de rayos X es un proceso cuántico estocástico donde el número de fotones detectados por unidad de tiempo sigue una distribución de Poisson. En el aire libre, la atenuación del haz es nula ($\\mu \\approx 0$). Al aplicar la fórmula Hounsfield calibrada respecto al agua:\n",
        "> $$\\text{HU} = 1000 \\times \\frac{0 - \\mu_{\\text{agua}}}{\\mu_{\\text{agua}}} = -1000\\text{ HU}$$\n",
        "\n",
        "#### 5. ¿Por qué la suma de pesos del kernel Gaussiano debe normalizarse obligatoriamente a exactamente 1.0?\n",
        "> **Respuesta Técnica:** En el dominio continuo $\\int_{-\\infty}^{\\infty} \\int_{-\\infty}^{\\infty} G(x,y) dx dy = 1$. Sin embargo, al truncar la campana en una rejilla discreta finita (ej. $3\\times 3$ o $5\\times 5$), la suma discreta de los coeficientes es significativamente inferior a 1. Si no se normaliza dividiendo cada elemento entre $\\sum K$, la convolución actuará como un atenuador de energía luminosa, oscureciendo progresivamente la imagen y alterando las Unidades Hounsfield de la TAC y las intensidades de RM.\n",
        "\n",
        "#### 6. ¿Qué ocurre con las dimensiones si `recuperar_bordes=False`?\n",
        "> **Respuesta Técnica:** Si no se aplica padding, el kernel $N \\times N$ solo puede centrarse en píxeles que tengan al menos $p = \\lfloor N/2 \\rfloor$ vecinos en todas direcciones. La matriz resultante pierde $p$ filas superiores, $p$ filas inferiores, $p$ columnas izquierdas y $p$ columnas derechas, reduciendo su tamaño a $(H - 2p) \\times (W - 2p)$. Con `recuperar_bordes=True`, el padding por reflexión espejo añade $p$ píxeles en cada borde antes de la convolución, preservando exactamente el tamaño $(H, W)$.\n",
        "\n",
        "#### 7. ¿Por qué el filtro de Mediana es superior para RM y TAC?\n",
