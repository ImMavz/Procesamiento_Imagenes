    add_code([
        "# ==============================================================================\n",
        "# FUNCIONES MÓDULO 3: HISTOGRAMA, CDF [0, 1] Y ECUALIZACIÓN DESDE CERO\n",
        "# ==============================================================================\n",
        "\n",
        "def calcular_histograma(imagen: np.ndarray, bins: int = 256, \n",
        "                        rango: tuple[float, float] = None) -> tuple[np.ndarray, np.ndarray]:\n",
        "    \"\"\"\n",
        "    Calcula el histograma discreto de frecuencias absolutas y los bordes de bins sin librerías externas.\n",
        "    \"\"\"\n",
        "    img = imagen.copy().astype(np.float64).flatten()\n",
        "    if len(img) == 0:\n",
        "        return np.zeros(bins, dtype=np.int64), np.zeros(bins + 1, dtype=np.float64)\n",
        "        \n",
        "    v_min = float(img.min()) if rango is None else float(rango[0])\n",
        "    v_max = float(img.max()) if rango is None else float(rango[1])\n",
        "    if v_min == v_max:\n",
        "        v_max += 1.0\n",
        "        \n",
        "    bin_width = (v_max - v_min) / bins\n",
        "    bin_edges = np.linspace(v_min, v_max, bins + 1)\n",
        "    \n",
        "    # Asignación manual de bin a cada píxel con función piso\n",
        "    indices = np.clip(np.floor((img - v_min) / bin_width).astype(np.int64), 0, bins - 1)\n",
        "    hist = np.zeros(bins, dtype=np.int64)\n",
        "    np.add.at(hist, indices, 1)\n",
        "    return hist, bin_edges\n",
        "\n",
        "\n",
        "def calcular_cdf(histograma: np.ndarray) -> np.ndarray:\n",
        "    \"\"\"\n",
        "    Calcula la Función de Distribución Acumulada (CDF) normalizada a probabilidad [0.0, 1.0]:\n",
        "        CDF[k] = sum_{i=0}^k hist[i] / total_pixeles\n",
        "    \"\"\"\n",
        "    hist = histograma.copy().astype(np.float64)\n",
        "    total = np.sum(hist)\n",
        "    return (np.cumsum(hist) / total) if total > 0 else np.zeros_like(hist)\n",
        "\n",
        "\n",
        "def interpolar_percentil(cdf: np.ndarray, bin_edges: np.ndarray, percentil: float = 0.8) -> float:\n",
        "    \"\"\"\n",
        "    Interpola el nivel de intensidad exacto correspondiente a una probabilidad acumulada dada (ej. 0.80 = 80%).\n",
        "    \"\"\"\n",
        "    centers = (bin_edges[:-1] + bin_edges[1:]) / 2.0\n",
        "    idx = np.searchsorted(cdf, percentil)\n",
        "    if idx == 0:\n",
        "        return float(centers[0])\n",
        "    if idx >= len(centers):\n",
        "        return float(centers[-1])\n",
        "    c0, c1 = cdf[idx - 1], cdf[idx]\n",
        "    v0, v1 = centers[idx - 1], centers[idx]\n",
        "    if c1 == c0:\n",
        "        return float(v0)\n",
        "    return float(v0 + (percentil - c0) / (c1 - c0) * (v1 - v0))\n",
        "\n",
        "\n",
        "def ecualizar_histograma_global(imagen: np.ndarray, bins: int = 256) -> np.ndarray:\n",
        "    \"\"\"\n",
        "    Ecualización Global de Histograma que linealiza la CDF conservando el rango físico original.\n",
        "    \"\"\"\n",
        "    img = imagen.copy().astype(np.float64)\n",
        "    orig_min, orig_max = img.min(), img.max()\n",
        "    if orig_max == orig_min:\n",
        "        return imagen.copy()\n",
        "        \n",
        "    # Mapeo a índices discretos\n",
        "    img_norm = np.clip((img - orig_min) / (orig_max - orig_min) * (bins - 1), 0, bins - 1)\n",
        "    indices = np.floor(img_norm).astype(np.int64)\n",
        "    \n",
        "    hist = np.zeros(bins, dtype=np.int64)\n",
        "    np.add.at(hist, indices.flatten(), 1)\n",
        "    \n",
        "    cdf = np.cumsum(hist) / np.sum(hist)\n",
        "    cdf_pos = cdf[cdf > 0]\n",
        "    cdf_min = cdf_pos[0] if len(cdf_pos) > 0 else 0.0\n",
        "    \n",
        "    denom = 1.0 - cdf_min\n",
        "    if denom == 0:\n",
        "        return imagen.copy()\n",
        "        \n",
        "    tabla_mapeo = np.round(((cdf - cdf_min) / denom) * (bins - 1))\n",
        "    img_eq_d = tabla_mapeo[indices]\n",
        "    \n",
        "    # Reescalado al rango dinámico nativo\n",
        "    img_eq = orig_min + (img_eq_d / (bins - 1)) * (orig_max - orig_min)\n",
        "    return img_eq\n"
    ])

