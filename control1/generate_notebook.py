        "Para modelar la firma física del ruido de los instrumentos, **nunca se utiliza la imagen completa**, pues la varianza anatómica de los bordes se confundiría con ruido. Se extrae una submatriz ($50\\times 50$ px) en regiones estrictamente homogéneas:\n",
